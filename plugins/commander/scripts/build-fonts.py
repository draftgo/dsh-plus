"""Build web subsets with fonttools[woff] and brotli; retain all supplied characters."""
from pathlib import Path
import copy
import hashlib
import io
import json
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools import subset

root = Path(__file__).resolve().parent.parent
source = root / 'assets/fonts/source/AlimamaFangYuanTiVF-Thin.ttf'
groups = {}
for cp in sorted(TTFont(source).getBestCmap()):
    key = 'latin' if cp < 0x3000 else f'u{cp // 256:02x}'
    groups.setdefault(key, []).append(cp)
output = root / 'assets/fonts/web'
output.mkdir(parents=True, exist_ok=True)
manifest, css = [], []
base = TTFont(source)
# Supplied STAT references absent axes; fvar retains the correct weight axis.
if 'STAT' in base:
    del base['STAT']
instantiateVariableFont(base, {'BEVL': 1}, inplace=True)
if 'gvar' in base:
    base['gvar'].variations = {g: base['gvar'].variations.get(g, []) for g in base.getGlyphOrder()}
for name, points in groups.items():
    font = copy.deepcopy(base)
    options = subset.Options()
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=points)
    sub.subset(font)
    font.flavor = 'woff2'
    stream = io.BytesIO()
    font.save(stream)
    data = stream.getvalue()
    digest = hashlib.sha256(data).hexdigest()[:12]
    filename = f'fangyuan-{name}-{digest}.woff2'
    (output / filename).write_bytes(data)
    ranges = []
    for cp in points:
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    unicode = ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in ranges)
    manifest.append({'file': filename, 'bytes': len(data), 'unicodeRange': unicode})
    css.append(f'@font-face {{ font-family: "Commander FangYuan"; font-style: normal; font-weight: 200 700; font-display: swap; src: url("./api/commander-fonts/{filename}") format("woff2"); unicode-range: {unicode}; }}')
css.append(':root { --dsh-font-family-text-default: "Commander FangYuan", -apple-system, BlinkMacSystemFont, "Segoe UI", "PingFang SC", "Microsoft YaHei", sans-serif; }')
(root / 'assets/fonts/manifest.json').write_text(json.dumps(manifest, indent=2) + chr(10))
active = {item['file'] for item in manifest}
for old in output.glob('fangyuan-*.woff2'):
    if old.name not in active:
        old.unlink()
(root / 'client/fonts.css').write_text('/* Generated by scripts/build-fonts.py; load only displayed characters. */' + chr(10) + chr(10).join(css) + chr(10))
print(f'{len(manifest)} subsets, {sum(x["bytes"] for x in manifest)} bytes total; Latin {manifest[0]["bytes"]} bytes', flush=True)
